"""Build the Frontier-only presentation dictionary and audit source/font coverage.

No authored GML, original NTTE translations, identity, or font asset is rewritten.
"""
from __future__ import annotations

import json
from pathlib import Path
import re

from fr_localization_inventory import ROOT, inventory

TAG = re.compile(r"@(?:[1-9]\([^)]*\)|\([^)]*\)|[A-Za-z])")
INTENTIONAL = {
    "Frontier", "pirate_conversions", "skill", "skill_text", "meals_eaten",
    "augments_taken", "caches_opened", "deeplabs_finales", "hoarder_kills",
    "hoarder_escapes", "cyberspace_visits", "pirate_trades", "bubbles_kills",
    "bubbles_loops", "bubbles_runs", "bubbles_deaths", "bubbles_wins",
    "bubbles_time", "bubbles_bubbles", "bubbles_best_kills",
    ":0)D-", "AEVUSONIAN", "CRINGERHOMBUS", "DRAGONSTRIVE", "GECKOBONE",
    "GOLDEN EPSILON", "JSBURG", "MCCHOMK", "SANIBLUES", "SQUIDDY", "YOKIN",
    "WIGGLERCOLA", "SPLATTIE",
}


def plain(text):
    text = TAG.sub("", text).replace("\r", "")
    # Source descriptions use both explicit line breaks and # separators.
    # Ignore indentation and the empty line between a newline and its #.
    text = re.sub(r"\s*(?:#|\n)\s*", " / ", text)
    text = re.sub(r"(?: / )+", " / ", text)
    return re.sub(r"[ \t]+", " ", text).strip()


def dictionary():
    result = {}
    for filename in ("surgery.zh-CN.tsv", "phrases.zh-CN.tsv", "settings.zh-CN.tsv"):
        path=ROOT/"localization"/filename
        if not path.is_file():
            continue
        for number,line in enumerate(path.read_text("utf-8").splitlines(), 1):
            if not line or line.startswith("#"):
                continue
            key,value=line.split("\t",1)
            key=plain(key)
            if key in result and filename != "phrases.zh-CN.tsv" and result[key] != value:
                raise ValueError(f"Conflicting localization at {filename}:{number}: {key}")
            result[key]=value
    return result


def audit(data=None):
    data = data or dictionary()
    rows=[]
    for source,sites in inventory().items():
        key=plain(source)
        if key in data:
            status="translated"
        elif not re.search(r"[A-Za-z]",key):
            status="format-or-number"
        elif key in INTENTIONAL:
            status="identity-or-credit"
        else:
            status="untranslated"
        rows.append({"source":source,"plain":key,"status":status,"sites":sites})
    glyphs={}
    text="".join(data.values())
    for name in ("fntCJK","fntCJKBig"):
        font=ROOT/"staging/project/fonts"/name/(name+".yy")
        available={int(value) for value in re.findall(r'"character":(\d+)',font.read_text("utf-8"))}
        missing=sorted({c for c in text if ord(c)>127 and not c.isspace() and ord(c) not in available})
        glyphs[name]={"checked_characters":len(set(text)),"missing":"".join(missing)}
    missing=[row for row in rows if row["status"]=="untranslated"]
    return {"status":"PASS" if not missing and not any(x["missing"] for x in glyphs.values()) else "FAIL",
            "dictionary_phrases":len(data),"inventory_literals":len(rows),
            "translated_literals":sum(row["status"]=="translated" for row in rows),
            "intentional_literals":sum(row["status"]=="identity-or-credit" for row in rows),
            "untranslated":missing,"fonts":glyphs,"inventory":rows}


def generate():
    data=dictionary()
    entries=",\n".join("        "+json.dumps(key,ensure_ascii=False)+": "+json.dumps(value,ensure_ascii=False)
                        for key,value in sorted(data.items()))
    source=("// Generated by tools/fr_localization_data.py from reviewed presentation TSVs.\n"
            "function scrFRLocalizationData() {\n    static _data={\n"+entries+"\n    };\n    return _data;\n}\n")
    (ROOT/"native/localization_data.gml").write_text(source,"utf-8",newline="\n")
    report=audit(data)
    (ROOT/"localization/coverage.json").write_text(json.dumps(report,ensure_ascii=False,indent=2)+"\n","utf-8")
    return report


if __name__=="__main__":
    result=generate()
    print(json.dumps({key:value for key,value in result.items() if key!="inventory"},ensure_ascii=True,indent=2))
