"""Names shared by the static compiler and the native compatibility layer."""
from pathlib import PurePosixPath


def module_key(source):
    path = PurePosixPath(source)
    for suffix, kind in [(".area.gml", "area"), (".wep.gml", "weapon"),
                         (".race.gml", "race"), (".skill.gml", "skill"),
                         (".crown.gml", "crown"), (".skin.gml", "skin")]:
        if path.name.endswith(suffix):
            return kind + ":" + path.name.removesuffix(suffix)
    return "mod:" + path.name.removesuffix(".mod.gml").removesuffix(".mod.ntgml")


def module_name(source):
    """The authored NTT name, distinct from the internal typed registry key."""
    return module_key(source).split(":", 1)[1]


